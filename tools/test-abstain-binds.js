// يحرس أن امتناعاً مُعلَناً يُلزم الكودَ الذي يليه — فلا يُتَّهم بندٌ بقياسٍ باطل.
//
// ⭐ **السؤال الذي يجيبه (بلغة المستخدم):** *«حين تقول أداتُنا «هذا القياس لا
// يُبنى عليه» ثمّ تقول في السطر التالي «الميزة معطوبة» — أيّهما أُصدّق؟»*
//
// ── العلّة التي وُلد منها (#104، مقيسةٌ 2026-08-04 في سحب «عند الطلب») ────────
// `tools/bench-91-title.mjs` كان يطبع **«⇒ القياس غير صالح — لا يُبنى عليه بند»**
// ثمّ يمضي فيطبع **«⇒ ❌ #91 قائم — والمفتاح يَعِد ولا يفي»** — **فيتّهم بنداً
// مغلقاً مؤكَّداً من المالك، بقياسٍ أعلن هو نفسُه بطلانه.**
// ⇒ ⭐ **وهو أسوأ من الابتلاع: الابتلاعُ يصمت، وهذا يقول «لا تصدّقني» ثمّ يتّهم.**
// ⇒ **وأخوه #103 من بابٍ آخر:** هناك **حالةٌ تُسجَّل ولا مُنادي**، وهنا **امتناعٌ
// يُعلَن ولا مُلزَم** — **وكلاهما «قِيل ولم يُنفَّذ»، والقولُ وحده لا يُغيّر مساراً.**
//
// ⚠️ **وحدُّه مُعلَن ولا يُوسَّع:** يحرس **الشكل في مواضعه المعروفة** — أن يقع
// خروجٌ غيرُ مشروطٍ بين إعلان البطلان وبين الحكم. ⛔ **ولا يزعم أنه يكتشف الشكلَ
// في رِكازٍ جديد** — **ذاك عملُ #105 حين يُوحَّد المخرَج**، وحتى ذلك الحين
// **المُطلِق: ثالثُ موضعٍ يُكشف بالقراءة** (كما في حدّ مسح «المُتحفَّظ عليه»).
const fs = require("fs");
const path = require("path");

let pass = 0, fail = 0;
const check = (name, cond, extra) => cond
  ? (pass++, console.log("  ✅ " + name))
  : (fail++, console.log("  ❌ " + name, extra === undefined ? "" : String(extra).slice(0, 200)));

const ROOT = path.join(__dirname, "..");

// **المواضع المعروفة، ولكلٍّ نصُّ بطلانه ونصُّ حكمه** — تُقرأ من الملفّ لا تُخمَّن.
const SITES = [
  { file: "bench-91-title.mjs",
    void: "القياس غير صالح — لا يُبنى عليه بند",
    verdict: "#91 قائم",
    why: "#104 — أُصلح 2026-08-04" }
];

// ── القاعدة، دالّةً نقيّة كي تُختبَر على عيّنةٍ كما تُختبَر على ملفّ ─────────
// **«يُلزم» = خروجٌ غيرُ مشروط بينهما**: `process.exit(...)` في سطرٍ ليس داخل
// تعليق، **بعد** إعلان البطلان و**قبل** طباعة الحكم.
function bindsAfter(rawSrc, voidText, verdictText) {
  // ⛔ **تُنزَع التعليقاتُ أوّلاً — وهذا ليس تفصيلاً:** أوّلُ تشغيلةٍ للحارس
  // احمرّت على الملفّ **المُصلَح**، لأن **شرحَ العطب في تعليقه يذكر نصَّ الحكم**
  // فوقعت المطابقةُ على التعليق قبل الكود. ⇒ ⭐ **مطابقةٌ أوسعُ من سؤالها، في
  // حارسٍ كُتب ضدّ الأوسعِ من سؤاله** — وهي ثالثةُ وقوعها في هذي الجلسة.
  const src = rawSrc.split("\n").map((l) => l.replace(/(^|\s)\/\/.*$/, "")).join("\n");
  const i = src.indexOf(voidText);
  const j = src.indexOf(verdictText);
  if (i < 0) return { ok: false, why: "نصُّ إعلان البطلان غائب" };
  if (j < 0) return { ok: true, why: "لا حكمَ بعده أصلاً" };
  if (j < i) return { ok: true, why: "الحكمُ قبل الإعلان لا بعده" };
  const between = src.slice(i, j);
  return { ok: /process\.exit\s*\(/.test(between),
           why: "لا خروجَ بينهما" };
}

console.log("\n[١] ⭐ الامتناعُ المُعلَن يُلزم ما بعده — ولا يُتَّهم بندٌ بقياسٍ باطل");
for (const s of SITES) {
  const p = path.join(ROOT, "tools", s.file);
  check(`\`${s.file}\` موجود`, fs.existsSync(p), s.file);
  if (!fs.existsSync(p)) continue;
  const src = fs.readFileSync(p, "utf8");
  const r = bindsAfter(src, s.void, s.verdict);
  check(`وامتناعُه يُلزم حكمَه (${s.why})`, r.ok, r.why);
  // **وسطرُ الامتناع يقول ماذا يعني** — فامتناعٌ صامت يُقرأ نجاحاً
  check("ويقول «امتنع» صراحةً لا يسكت", /امتنع/.test(src));
}

console.log("\n[٢] شاهدا قرار 26 — على الحارس نفسه");
{
  const V = "القياس غير صالح", J = "#91 قائم";
  // **سالب: الشكلُ السابق بنصّه** — إعلانٌ ثمّ حكمٌ بلا خروج
  const before = `console.log("⇒ ${V}");\nconsole.log("⇒ ${J}");`;
  check("سالب: الشكلُ السابق يُحمَّر", !bindsAfter(before, V, J).ok);
  // **موجب: وبينهما خروج**
  const after = `console.log("⇒ ${V}");\nif (!ok) { console.log("⚪ امتنع"); process.exit(1); }\nconsole.log("⇒ ${J}");`;
  check("موجب: وبخروجٍ بينهما يمرّ", bindsAfter(after, V, J).ok);
  // **وثالث: خروجٌ في تعليقٍ لا يُحتسب** — وإلا مرّ الشكلُ بذكر الاسم وحده
  const commented = `console.log("⇒ ${V}");\n// process.exit(1) — مذكورٌ في تعليق\nconsole.log("⇒ ${J}");`;
  check("وثالث: خروجٌ داخل تعليق لا يُحتسب", !bindsAfter(commented, V, J).ok);
  // **ورابع: ولا حكمَ ⇒ لا شيء يُحرَس** — فالحارس لا يُحمّر على ما ليس فيه الشكل
  check("ورابع: ملفٌّ بلا حكمٍ بعده يمرّ", bindsAfter(`console.log("⇒ ${V}");`, V, J).ok);
}

console.log(`\n${fail === 0 ? "✅" : "❌"} نجح ${pass} / فشل ${fail}\n`);
process.exit(fail ? 1 : 0);
