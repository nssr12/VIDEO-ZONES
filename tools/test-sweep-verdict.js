// يحرس أحكام اجتياح قسم [٣]: لا خضرةَ عن اجتياحٍ خاوٍ، ولا ضابطَ يخرج منه صامتاً.
//
// ⭐ **السؤال الذي يجيبه (بلغة المستخدم):** *«حين تقول البوّابةُ إن ضوابط
// الإعدادات سليمة — أعن ستّةٍ وأربعين تحقّقت، أم عن لا شيء؟»*
//
// ── العلّة التي وُلد منها (2026-08-04، بعد إغلاق شطرَي #93) ──────────────────
// **صنفٌ واحد: بوّابةٌ خضراء عن لا شيء** — رُصد **أربع مرّات في اليوم نفسه وفي
// `bench-options-page.mjs` بعينه**. ⇒ **فلم يعد شكّاً** (قرار المالك:
// **«بندٌ بلا عَرَضٍ مرصود شكّ» تُقاس بالصنف لا بالحالة** — وصنفُهما مرصود،
// وما بقي هو الحالة لا الصنف).
//   · **`sw.length` كان يُطبع ولا يُؤكَّد**، والشروطُ الثلاثة تُصفّي مصفوفة —
//     **ومصفوفةٌ خاوية تُرضيها كلَّها**.
//   · **و«مُتخطّى» كان سطرَ طباعةٍ لا شرطاً**، ومُطلِقُه **فعلٌ عاديّ**:
//     `volumeDuration` عند `0` يُعطّل `speedBadgeEnabled` وهو يُجتاح بعده.
//
// ⚠️ **ولماذا يُحرَس هنا لا في الرِكاز:** الرِكاز يحتاج كروم، **وحارسٌ يحتاج
// مضيفاً هو حارسٌ يُشغَّل عند الطلب** — وقد نامت #103 في واحدٍ منها أسابيع.
// **فالحكمُ نقيٌّ في `sweep-verdict.mjs` يُحرَس قبل كل كومِت، والقياسُ يُطعمه.**
let pass = 0, fail = 0;
const check = (name, cond, extra) => cond
  ? (pass++, console.log("  ✅ " + name))
  : (fail++, console.log("  ❌ " + name, extra === undefined ? "" : JSON.stringify(extra)));

const DRAWN = { clean: 38, timing: 8 };            // كما قِيس على الصفحة الحيّة
const row = (id, over = {}) => ({ id, ok: true, changed: true, threw: 0, ...over });
const healthy = () => Array.from({ length: 46 }, (_, i) => row("c" + i));
const reds = (vs) => vs.filter((v) => !v.ok).map((v) => v.name);

const main = async () => {
  const { sweepVerdicts } = await import("./sweep-verdict.mjs");
  const V = (sweep, drawn = DRAWN) => sweepVerdicts(sweep, drawn);

  console.log("\n[1] شاهدٌ موجب — الاجتياحُ السليم يمرّ كلُّه");
  {
    const v = V(healthy());
    check("خمسةُ أحكامٍ تُرجَع", v.length === 5, v.length);
    check("وصفر أحمر — فالحارس لا يُحمّر على كلّ شيء", reds(v).length === 0, reds(v));
  }

  console.log("\n[2] ⭐ الشاهد الأوّل: **اجتياحٌ خاوٍ يُحمّر**");
  {
    // ⛔ **وهذا هو العطب بعينه**: الشروطُ الثلاثة القديمة تُصفّي مصفوفةً خاوية
    // إلى صفر **فتُطبع خضراء كلُّها** — والحكمُ الأوّل وحده يمنع ذلك.
    const v = V([]);
    check("**الخاوي يُحمّر**", reds(v).length > 0, reds(v));
    check("ويُحمّر حكمَ الشمول بعينه", !v[0].ok, v[0]);
    check("والدليلُ يحمل العددين (اجتيح · رُسم)",
      v[0].extra?.اجتيح === 0 && v[0].extra?.رُسم === 46, v[0].extra);
    // **وشاهدٌ سالبٌ للحكم نفسه**: الثلاثةُ الأخرى **راضيةٌ عن الخاوي** — وهو
    // ما يُثبت أن الحكم الأوّل ليس تكراراً لها بل يسدّ ما لا تراه.
    check("⭐ والثلاثةُ الأخرى راضيةٌ عنه — فالحكمُ الأوّل ليس تكراراً",
      v.slice(1).every((x) => x.ok), reds(v.slice(1)));
  }

  console.log("\n[3] ⭐ الشاهد الثاني: **ضابطٌ مُعطَّلٌ يُجتاح فيُحمّر**");
  {
    // الحالُ المقيسة: `volumeDuration` عند `0` يُعطّل `speedBadgeEnabled`،
    // فيُرجع الاجتياحُ `{ skipped: true }` — **صفٌّ بلا `ok`**.
    const sw = healthy();
    sw[3] = { id: "speedBadgeEnabled", skipped: true };
    const v = V(sw);
    check("**المُعطَّل يُحمّر**", reds(v).length > 0, reds(v));
    check("ويُحمّر حكمَ الخروج بعينه", !v[4].ok, v[4]);
    check("والدليلُ يُسمّيه بمعرّفه لا بعدده",
      String(JSON.stringify(v[4].extra)).includes("speedBadgeEnabled"), v[4].extra);
    check("⭐ والأحكامُ الثلاثة القديمة راضيةٌ عنه — وهو ما كان يُخفيه",
      v[1].ok && v[2].ok && v[3].ok, reds([v[1], v[2], v[3]]));
    check("وغيرُ المرسوم كذلك (`why`)", !V(healthy().map((r, i) =>
      i === 7 ? { id: "cp_x", why: "غير مرسوم" } : r))[4].ok);
  }

  console.log("\n[4] وعددٌ ناقص يُحمّر — لا الخاوي وحده");
  {
    check("45 من 46 يُحمّر", !V(healthy().slice(0, 45))[0].ok);
    check("و47 يُحمّر كذلك — فالشرطُ مطابقةٌ لا حدٌّ أدنى",
      !V([...healthy(), row("زائد")])[0].ok);
    // ⛔ **ولا يشهد العددُ لنفسه**: لو غاب المصدر الثاني (ما رُسم) لَصار
    // «46 = 46» تحصيلَ حاصل. فغيابُه يُحمّر ولا يُقرأ سلامة.
    check("⭐ وغيابُ المصدر الثاني يُحمّر — فلا يشهد العددُ لنفسه",
      !V(healthy(), {})[0].ok && !V(healthy(), null)[0].ok);
  }

  console.log("\n[5] والأحكامُ الثلاثة القديمة ما زالت تُحمّر — فالنقلُ لم يُضعفها");
  {
    check("رميةُ ضابطٍ تُحمّر",
      !V(healthy().map((r, i) => i === 2 ? row("x", { threw: 1, msg: "رمى" }) : r))[1].ok);
    check("وتبديلٌ لا يصل التخزين يُحمّر",
      !V(healthy().map((r, i) => i === 2 ? row("x", { changed: false }) : r))[2].ok);
    check("وقفزةُ #89 تُحمّر",
      !V(healthy().map((r, i) => i === 2
        ? row("idleDuration", { wanted: "100", shown: "500" }) : r))[3].ok);
    check("⭐ وقيمةٌ مطابقة لا تُحمّر — فالشرطُ يُميّز",
      V(healthy().map((r, i) => i === 2
        ? row("idleDuration", { wanted: "100", shown: "100" }) : r))[3].ok);
  }

  console.log(`\n${fail === 0 ? "✅" : "❌"} نجح ${pass} / فشل ${fail}\n`);
  process.exit(fail ? 1 : 0);
};
main();
