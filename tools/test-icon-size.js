// كلُّ أيقونةٍ نشحنها لها قاعدةُ مقاسٍ صريحة — وإلا انهارت حيث لا أنماطَ لنا
//
// ⭐ **السؤال الذي يجيبه (بلغة المستخدم):** *«الزرُّ الذي أراه في شريط يوتيوب —
// أهو زرٌّ أم شريطٌ رفيعٌ بلا صورة؟»*
//
// ── ⛔ الواقعة التي وُلد منها (2026-08-06، #108) ─────────────────────────────
// **زرُّ الفلاتر حُقن في `.ytp-right-controls` ولم يُخفَ — وعرضُه `12px`
// وأيقونتُه `0×0`، وجارُه `56`.** ⇒ **موجودٌ ولا يُرى**، **ولا رميةَ ولا تحذير**
// ⇒ **مرّ من كل ما بنيناه، لأن كلَّه يفحص ما يُقال لا ما يُرى.**
//
// **والسببُ قِيس ولم يُخمَّن** (مِجَسّ `probe-108-button.js` في متصفّح المالك):
// **«لا قاعدةَ تضبط مقاسَها»** · و`getComputedStyle` **`0px×0px`** · والسمتان
// `width`/`height` **غائبتان** و`viewBox` وحدَه حاضر.
// ⇒ ⭐ **والحكمُ للمحسوب لا للعدد**: 19 ورقةً مقروءة و3 محجوبة — **والمحسوبُ
// يقول ما فاز أياً كانت ورقتُه**، فالمحجوبةُ لا تُغيّره. **وعدُّها بدل ابتلاعها
// هو ما جعل هذا مقروءاً** (قرار المالك).
// ⇒ **فالجواب (ب): قاعدتُنا ناقصة، ولا قاعدةَ مضيفٍ تفوز** ⇒ **سطرٌ يُضاف،
// ولا حدَّ يُكتب** (قرار المالك: لا يُعمَّم ما لم يُقس).
//
// ⭐ **ولغزُ «24×24 محلياً» انحلّ ولم يُترك:** الأيقونةُ تأخذ مقاسَها **من
// حاويتها** — **في طبقتنا `.vzBtn` تُعطيه (`min-width:44px; height:40px`)،
// وفي شريط المضيف `.vzInBar` تُلغي ذلك كلَّه** (`min-width:0; position:static`)
// **فلا يبقى ما يُعطيها مقاساً.** ⇒ **فالقياسُ المحليّ لم يكن خاطئاً — كان عن
// حالٍ أخرى** (قرار 106: النفيُ يُقيَّد بشروط قياسه).
//
// ── ⭐ ولماذا فحصٌ ساكن لا رِكاز (قرار المالك 2026-08-06) ────────────────────
// **تأكيدُ الحضور في `bench-content-errors` لا يستطيع أن يُحمّر محلياً**: الزرّ
// يسقط إلى طبقتنا فيُرى بـ44، **وضمورُه لا يقع إلا في شريط المضيف** — و#112
// (لا رِكازَ على يوتيوب الحقيقيّ) **مفتوح**.
// ⇒ **والماسكُ ممكنٌ بلا مضيفٍ أصلاً: كلُّ صنف أيقونةٍ له قاعدةٌ بمقاسه** —
// **لا متصفّح، ولا شبكة، وحتميٌّ في أجزاء الثانية.**
// ⭐ **وهو يمسك الصنفَ كلَّه لا هذي الواقعة: أيقونةٌ رابعةٌ تُضاف غداً بلا قاعدة
// تُحمّر قبل أن تُشحن.**
const fs = require("fs");

const SRC = fs.readFileSync("content.js", "utf8");

let pass = 0, fail = 0;
const check = (name, cond, extra) => cond
  ? (pass++, console.log("  ✅ " + name))
  : (fail++, console.log("  ❌ " + name, extra ?? ""));

console.log("\n=== أيقوناتُنا: لكلّ صنفٍ قاعدةُ مقاس ===\n");

// **الأصناف تُقرأ من الكود لا من قائمةٍ نكتبها** — فأيقونةٌ جديدة تدخل الفحص
// بنفسها، ولا تنتظر أن يتذكّرها أحد.
// ⚠️ **والصنفُ صار يُعلَن في نداء الراسم لا في وسمٍ مكتوب** (#131): الوسمُ يُبنى
// بـ`vzSvg` **فلا `class="…"` حرفيّاً في المصدر** — ⇒ **فيُقرأ الصنفُ من موضعه
// الجديد**، **ولولا هذا لَقرأ الحارسُ صفراً وقال «لا أيقونةَ تُشحن» وهي تُشحن**
// (وهو الصفرُ الذي لا يُفصل مصدره: «لا يوجد» و«لا أرى» يطبعان الرقم نفسه).
const classes = [...new Set([
  ...[...SRC.matchAll(/class="(vz[A-Za-z]*Icon)"/g)].map((m) => m[1]),
  ...[...SRC.matchAll(/cls:\s*"(vz[A-Za-z]*Icon)"/g)].map((m) => m[1])
])].sort();

check("[1] أصنافُ الأيقونات تُقرأ من الكود", classes.length > 0, classes);
console.log(`     المشحونة: ${classes.length} · ${classes.join(" · ")}`);

// **قاعدةٌ صريحة**: تضبط `width` و`height` معاً — فأحدُهما وحده يترك الآخر للحاوية،
// وهي التي تختفي داخل شريط المضيف.
const ruleFor = (cls) => {
  const m = SRC.match(new RegExp(`\\.${cls}\\s*\\{([^}]*)\\}`));
  return m ? m[1] : null;
};

const missing = [];
for (const cls of classes) {
  const body = ruleFor(cls);
  const hasW = !!body && /(^|[;\s])width\s*:\s*\d/.test(body);
  const hasH = !!body && /(^|[;\s])height\s*:\s*\d/.test(body);
  check(`[2] \`.${cls}\` لها قاعدةٌ بمقاسٍ صريح (عرضاً وارتفاعاً)`, hasW && hasH,
    body === null ? "**لا قاعدةَ إطلاقاً**" : body.trim().slice(0, 70));
  if (!(hasW && hasH)) missing.push(cls);
}
check(`[2] ⭐ ولا صنفَ بلا مقاس (${classes.length - missing.length}/${classes.length})`,
  missing.length === 0, missing);

// ── [3] ⭐ الشاهدان (قرار 26 · 47) — على المنطق نفسِه لا على شبيهٍ يُفتعَل ────
// **حارسٌ يمرّ ولا يستطيع أن يُحمّر يُقرأ خضارُه سلامةً وهو عمى.**
console.log("\n[3] ⭐ الشاهدان: يرى القاعدة ويرى غيابها");
{
  const probe = (css, cls) => {
    const m = css.match(new RegExp(`\\.${cls}\\s*\\{([^}]*)\\}`));
    const b = m ? m[1] : null;
    return !!b && /(^|[;\s])width\s*:\s*\d/.test(b) && /(^|[;\s])height\s*:\s*\d/.test(b);
  };
  check("[3] سالب: قاعدةٌ تامّة تمرّ",
    probe(".vzXIcon{ width:24px; height:24px; }", "vzXIcon") === true);
  check("[3] ⭐ موجب: لا قاعدةَ إطلاقاً ⇒ يُكشف",
    probe(".vzOther{ color:#fff; }", "vzXIcon") === false);
  check("[3] ⭐ وموجبٌ ثانٍ: عرضٌ بلا ارتفاع ⇒ يُكشف",
    probe(".vzXIcon{ width:24px; }", "vzXIcon") === false,
    "**وأحدُهما وحده يترك الآخر للحاوية — وهي التي تختفي في شريط المضيف**");
}

// ── [4] والسجلُّ يوافق الكود: ما يُشحن له صنفٌ مرسوم ────────────────────────
console.log("\n[4] وسجلُّ الأيقونات يوافق ما يُرسم");
{
  const shipped = require("./icons.js").VZ_ICONS_SHIPPED;
  check("[4] السجلّ يُقرأ", Array.isArray(shipped) && shipped.length > 0, shipped);
  check("[4] ⭐ وعددُ الأصناف المرسومة يطابق عددَ المشحون",
    classes.length === shipped.length, { أصناف: classes.length, مشحون: shipped.length });
}

console.log(`\n${fail === 0 ? "✅" : "❌"} نجح ${pass} / فشل ${fail}\n`);
process.exit(fail ? 1 : 0);
