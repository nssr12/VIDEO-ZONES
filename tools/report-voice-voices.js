//
// ── ⛔ الشاهدان — ولا حكمَ بدونهما (قرار 26 · قرار 150) ─────────────────────────
//  · **سالبٌ على المرشِّح:** قائمةٌ اصطناعيّة فيها ثلاثةُ أسماءٍ تحوي «ar» ولغتُها
//    غيرُ عربيّة (Bulgarian · Standard · Arabella) وصوتان عربيّان بصيغتَي الوسم
//    (`ar-001` · `ar_SA`) ⇒ **يجب أن يُرجع Majed وNaayf بالضبط، وإلا ⛔ ولا يُعدّ
//    صوت.** (درس #161: «ar» يطابق «Bulgarian» ⇒ **الوسمُ الأوّلُ للّغة، لا الاسم.**)
//  · **موجبٌ على القائمة:** عددُ الأصوات كلِّها > 0 ⇒ **المِجَسُّ يرى القائمة** — ⛔ **و❌ يشترط
//    صوتاً محلّيّاً واحداً على الأقلّ** (`localService`): **الدفعةُ الأولى المقيسة (19) هي أصواتُ
//    كروم الشبكيّة وحدَها على الأرجح** (عددُ أصوات «Google» الشبكيّة نفسُه) ⇒ **«غيرُ فارغة» لا تثبت
//    أنّ أصواتَ النظام وصلت.** ⛔ **وبدونه فصفرُ العربيّة صمتٌ لا قياس: «لا يوجد» و«لا أرى» يطبعان
//    الصفرَ نفسَه** — **والقائمةُ فارغةٌ فعلاً قبل `voiceschanged`.**
//  · **وشاهدٌ حيٌّ يُطبع رقماً لا شرطاً:** أصواتُ هذا الجهاز التي في اسمها «ar»
//    وليست عربيّة (فخُّ الاسم) ⇒ **رفضها المرشِّح على قائمةٍ حقيقيّة لا مصنوعة.**
//
// ── ⚠️ حدودٌ مُعلَنة ────────────────────────────────────────────────────────────
//  · **«في القائمة» ليس «ينطق»** (قرار 109): **لا يُنطق هنا حرف** — النطقُ وزمنُه
//    وسرعتُه للمِجَسّين 3 و4.
//  · ⛔ **`voiceschanged` الأوّلُ قد يحمل قائمةً ناقصة** — قِيس 2026-10-31 (كروم 156 بلا
//    واجهة على هذا الماك، أوّلَ تشغيلٍ للعمليّة): **@8ms بـ19 صوتاً وصفرِ عربيّ، ثمّ
//    @1564ms بـ200 وعربيّين** ⇒ **حكمٌ عند أوّل قائمةٍ غيرِ فارغة كان سيطبع ❌ كاذباً.**
//    ⇒ **فلا حكمَ قبل 5 ثوانٍ وسكونِ القائمة ثانيةً كاملةً وفيها صوتٌ محلّيّ** (والسقفُ 7)، **ويُطبع كلُّ
//    حدثٍ بوقته وعدده لحظةَ وقوعه.** ⚠️ **ولصقٌ ثانٍ في الصفحة نفسِها يجد القائمةَ ولا
//    يُطلَق الحدثُ أصلاً** (قِيس) — **والأرقامُ الثلاثة ونبضُ 250ms اختياراتُ تصميمٍ لا
//    قياس** (قرار 96).
//  · **كروم يعدّ أصواتَ النظام مرّةً في عمر العمليّة** (§٣، 📖) ⇒ صوتٌ أُضيف وكروم
//    يعمل لا يظهر حتى الخروجِ منه — **وعلى الماك إغلاقُ النوافذ لا يُنهيه: ⌘Q.**
//  · ⛔ **والأسماءُ تتبع لغةَ الواجهة على الماك أيضاً، لا على الويندوز وحدَه** — قِيس
//    2026-10-31 (كروم 156 بلا واجهة على هذا الماك): «ماجد» و«ليلى (محسّن)» لا Majed
//    وLaila، **وفي أوّل الثاني علامةُ اتّجاهٍ خفيّة U+200F.** ⇒ **فلا يُطابَق اسمٌ هنا
//    أبداً** (أوّلُ صياغةٍ قارنت بـ§٩ بالاسم **فطبعت «لا» لصوتين حاضرين**)، **وتُظهَر
//    العلاماتُ الخفيّة في السطر ⟨U+…⟩** — والمقارنةُ بـ§٩ تُقرأ بالعين.
//  · **صوتٌ بلا وسمِ لغة، أو يقول اسمُه «Arabic/عربيّ» ووسمُه غيرُ `ar`، لا يحكم عليه
//    المرشِّح** ⇒ **يُسمّى في حقل «مشتبَه» ولا يُحتسب عربيّاً ولا فخّاً.**
//  · **«الموسومُ‑افتراضيّاً» ما يَسِمه كروم بـ`default`** — ولا يُدّعى أنه صوتُ
//    النظام: **اسمُ الحقل لا يكون أوسعَ من قياسه.**
//  · لا كتابةَ في التخزين ولا طلبَ شبكةٍ ولا لمسَ للصفحة، **ومستمعُ `voiceschanged`
//    يُزال في كلّ مخرج.**
//
// ── كيف يُستعمل ─────────────────────────────────────────────────────────────────
//   1) افتح أيَّ صفحةٍ في كروم — صفحةُ مشاهدةٍ على يوتيوب تكفي. **وأيُّ سياقٍ
//      للكونسول يصلح** (الصفحة · الإضافة · صفحةُ إعداداتها): القائمةُ للمتصفّح كلِّه.
//   2) افتح الكونسول (F12 على الويندوز · ⌥⌘J على الماك).
//   3) الصق هذا الملفَّ كلَّه واضغط Enter — يطبع 🟢، ثمّ بعد 5 ثوانٍ (حتى 7) سطراً
//      واحداً يبدأ بـ VZ-168أ-2 وينسخه إلى الحافظة.
//   4) أعِده على الجهاز الآخر (الماك ثمّ الويندوز)، وأرسل السطرين كما هما.
//   5) **إن طبع ❌ فأضفتَ صوتاً عربيّاً من إعدادات النظام:** اخرج من كروم كلِّه وأعِد
//      تشغيله ثمّ أعِد اللصق — **وسجّل أكان الصوتُ مثبّتاً سلفاً** (§٦).
(async () => {
  const TAG = "VZ-168أ-2";
  // ⛔ **`copy` تُلتقط قبل أوّل `await`** — قِيس 2026-10-31 على كروم 156: `typeof copy`
  // = `function` قبل الانتظار و`undefined` بعده (أدواتُ الكونسول تُركَّب للتقييم
  // المتزامن وحدَه) ⇒ **نداؤها بعد الانتظار لا ينسخ شيئاً، والرميةُ تُبتلع صامتة.**
  const copyFn = typeof copy === "function" ? copy : null;
  const t0 = performance.now();
  const ms = () => Math.round(performance.now() - t0);
  const sleep = (n) => new Promise((r) => setTimeout(r, n));
  const POLL_MS = 250, EMPTY_MS = 5000, QUIET_MS = 1000, CAP_MS = 7000;   // 🎯 قرار 96
  const emit = (line) => {
    console.log(line);
    try { copyFn(line); console.log("   (نُسخ إلى الحافظة)"); } catch (e) {}
  };
  // العلاماتُ الخفيّة تُكتب ولا تُخفى — وإلا فسطرٌ يُقرأ غيرَ ما فيه · ⛔ **ونطاقُها بالترميز لا بالحروف نفسِها:**
  // حرفُ U+202E خفيٌّ يقلب عرضَ السطر في المحرّر (صنفُ «Trojan Source») · وU+061C علامةُ اتّجاهٍ عربيّة
  const vis = (s) => String(s).replace(/[\u061C\u200B-\u200F\u202A-\u202E\u2060\u2066-\u2069\uFEFF]/g,
    (c) => "⟨U+" + c.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0") + "⟩");

  // ── السياق: يُطبع ولا يُرفض — القائمةُ للمتصفّح كلِّه ─────────────────────────
  const ctx = location.protocol === "chrome-extension:" ? "صفحة-الإضافة " + location.pathname
    : (typeof globalThis.extensionActive === "function" ? "عالم-الإضافة" : "عالم-الصفحة") +
      " (" + (location.hostname || location.protocol) + ")";

  // ── ⭐ المرشِّح: الوسمُ الأوّلُ للّغة بالضبط — لا الاسم (درس #161) ─────────────
  const isArabic = (v) => (v.lang || "").toLowerCase().split(/[-_]/)[0] === "ar";
  const nameHasAr = (v) => /ar/i.test(v.name || "");
  // ── وشاهدُه السالب: قائمةٌ اصطناعيّةٌ جوابُها معلومٌ قبل أن تُقرأ ──────────────
  const SYN = [{ name: "Bulgarian", lang: "bg-BG" }, { name: "Standard", lang: "en-US" },
    { name: "Arabella", lang: "en-GB" }, { name: "Majed", lang: "ar-001" }, { name: "Naayf", lang: "ar_SA" }];
  const synAr = SYN.filter(isArabic).map((v) => v.name).join("·");
  const filterOk = synAr === "Majed·Naayf";
  const wNeg = "الوسمُ⇐" + (synAr || "لا شيء") + " والاسمُ«ar»⇐" +
    SYN.filter(nameHasAr).map((v) => v.name).join("·");

  // ── التحميلُ يبدأ متزامناً قبل أيّ انتظار — فلا يفوت `voiceschanged` ─────────
  const ss = globalThis.speechSynthesis;
  const hasSS = !!ss && typeof ss.getVoices === "function";
  let vcN = 0, firstAt = -1, firstN = 0, listening = false, envText = "لم تُقرأ";
  const evs = [];               // كلُّ حدث: متى · كم صوتاً · كم عربيّاً — لحظةَ وقوعه
  const onVC = () => {
    const l = ss.getVoices() || [];
    vcN++;
    if (l.length && firstAt < 0) { firstAt = ms(); firstN = l.length; }
    if (evs.length < 5) evs.push("@" + ms() + "ms⇐" + l.length + "/محلّيّ" + l.filter((v) => v.localService).length +
      "/ع" + l.filter(isArabic).length);
  };
  console.log("🟢 " + TAG + ": أقرأ قائمةَ أصوات كروم وأنتظر سكونَها — السطرُ بعد 5 ثوانٍ (حتى 7).");
  try {
    const atPaste = hasSS && filterOk ? (ss.getVoices() || []).length : 0;
    if (hasSS && filterOk) { ss.addEventListener("voiceschanged", onVC); listening = true; }

    // ── البيئة: من تلميحات المتصفّح عالية الدقّة، وإلا فسلسلةُ الوكيل كما هي ────
    let to = 0;
    try {
      const uad = navigator.userAgentData;
      if (!uad || typeof uad.getHighEntropyValues !== "function") throw new Error("navigator.userAgentData غائب");
      const h = await Promise.race([uad.getHighEntropyValues(["platform", "platformVersion",
        "architecture", "bitness", "fullVersionList"]),
        new Promise((_, rej) => { to = setTimeout(() => rej(new Error("مهلة 2000ms")), 2000); })]);
      const os = h.platform || "?", pv = h.platformVersion || "", major = parseInt(pv, 10);
      const ver = os === "Windows"                       // 13+ = ويندوز 11 · 1–12 = ويندوز 10
        ? (major >= 13 ? "11" : major > 0 ? "10" : "7/8") + " (" + pv + ")" : pv.replace(/\.0$/, "");
      const arch = h.architecture === "x86" ? (h.bitness === "64" ? "x64" : "x86")
        : (h.architecture || "?") + (h.bitness === "64" ? "64" : "");
      const list = h.fullVersionList || [];
      const b = list.find((x) => x.brand === "Google Chrome") ||
        list.find((x) => x.brand !== "Chromium" && !/not.?a.?brand/i.test(x.brand)) ||
        list.find((x) => x.brand === "Chromium") || { brand: "?", version: "?" };
      envText = os + " " + ver + " " + arch + " · " +
        (b.brand === "Google Chrome" ? "Chrome" : b.brand) + " " + b.version;
    } catch (e) {
      envText = "UA=" + navigator.userAgent + " (UA-CH: " + ((e && e.message) || e) +
        ") ⚠️ سلسلةٌ مُجمَّدة: نظامُها وإصدارُه فيها غيرُ حقيقيّين";   // قِيس: «Intel 10_15_7» على ماك arm64 بإصدار 26.2
    } finally { clearTimeout(to); }
    const tail = " · سياق=" + ctx + " · بيئة: " + envText;

    // ── ⛔ الرفضُ يُسمّي شرطَه بقيمته (قرار 140) ──────────────────────────────────
    if (!filterOk) {
      emit(TAG + " ⛔ **المرشِّح معطوب** — على القائمة الاصطناعيّة: " + wNeg +
        "، والمطلوب Majed·Naayf بالضبط ⇒ **لا يُعدّ صوتٌ بمرشِّحٍ لم يُثبت أنه يميّز** (قرار 26)" + tail);
      return;
    }
    if (!hasSS) {
      emit(TAG + " ⛔ لا واجهةَ نطقٍ في هذا السياق: speechSynthesis = " +
        (ss ? "موجودٌ بلا getVoices" : "«" + typeof ss + "»") +
        " — والمطلوب كروم سطح المكتب في تبويبٍ عاديّ؛ أعِد اللصق هناك" + tail);
      return;
    }

    // ── الانتظار: 5 ثوانٍ على الأقلّ، ثمّ حتى تسكن القائمةُ ثانيةً (والسقفُ 7) ────
    // **فالقائمةُ قد تصل على دفعات، وصفرٌ يُقرأ بين دفعتين صفرٌ كاذب** (قرار 150).
    if (!atPaste) console.log("🟡 " + TAG + ": القائمةُ فارغةٌ عند اللصق — أنتظر voiceschanged (حتى 5 ثوانٍ).");
    let voices = [], sig = "", changedAt = 0, el = 0;
    for (;;) {
      voices = ss.getVoices() || [];
      el = ms();
      const s = voices.map((v) => v.name + "|" + v.lang + "|" + v.voiceURI).join("\n");
      if (s !== sig) { sig = s; changedAt = el; }
      if (voices.length && firstAt < 0) { firstAt = el; firstN = voices.length; }
      // وقائمةٌ شبكيّةٌ وحدَها تُنتظر حتى السقف — أصواتُ النظام تصل بعدها (قرار 150)
      if (el >= EMPTY_MS && (!voices.length || (el - changedAt >= QUIET_MS && voices.some((v) => v.localService)))) break;
      if (el >= CAP_MS) break;
      await sleep(POLL_MS);
    }
    const quiet = el - changedAt;
    const load = "voiceschanged=" + (vcN ? "×" + vcN + " [" + evs.join(" · ") +
      (vcN > evs.length ? " · …" : "") + "]" : "لم يُطلَق") + " · عند‑اللصق=" + atPaste +
      " · أوّلُ‑غيرِ‑فارغة=" + (firstAt < 0 ? "—" : "@" + firstAt + "ms⇐" + firstN) +
      " · آخرُ‑تغيّر=@" + changedAt + "ms · سكون=" + quiet + "ms";
    if (!voices.length) {
      emit(TAG + " ⛔ القائمة فارغة بعد 5 ثوانٍ — «لا يوجد» و«لم يُحمَّل» يطبعان الصفرَ نفسَه (قرار 26): " +
        "أعد اللصق بعد ثوانٍ، وإن تكرّر فاخرج من كروم وأعد تشغيله ⇒ " + load +
        " · شاهد−=✅ " + wNeg + " · شاهد+=❌ القائمة 0" + tail);
      return;
    }

    // ── القراءة: العربيّةُ بالوسم، وما فات المرشِّحَ مُسمّىً، وفخُّ الاسم رقماً ────
    const ar = voices.filter(isArabic);
    const sus = voices.filter((v) => !isArabic(v) &&
      (!(v.lang || "").trim() || /arabic|عرب/i.test(v.name || "")));
    const trap = voices.filter((v) => !isArabic(v) && !sus.includes(v) && nameHasAr(v)).length;
    const fmt = (v) => vis(v.name) + "|" + (v.lang || "بلا‑وسم") + "|" +
      (v.localService ? "محلّيّ" : "شبكيّ") + "|افتراضيّ=" + (v.default ? "نعم" : "لا");
    const dflt = voices.find((v) => v.default), local = voices.filter((v) => v.localService).length;
    const facts = "الموسومُ‑افتراضيّاً=" + (dflt ? vis(dflt.name) + "|" + dflt.lang : "لا أحد") +
      " · فخُّ‑الاسم=" + trap + " (في اسمها «ar» وليست عربيّة ⇐ رفضها المرشِّح)" +
      " · مشتبَه=" + sus.length + (sus.length ? " [" + sus.slice(0, 3)
        .map((v) => vis(v.name) + "|" + (v.lang || "بلا‑وسم")).join(" ، ") + "]" : "") +
      " · " + load + " · شاهد−=✅ " + wNeg + " · شاهد+=" + (local ? "✅" : "⚠️") + " القائمة " + voices.length +
      " > 0 · محلّيّ=" + local + tail;

    // ── الحكم ─────────────────────────────────────────────────────────────────────
    if (ar.length) {
      emit(TAG + " ✅ **كروم يرى " + ar.length + " صوتاً عربيّاً من " + voices.length + "**: " +
        ar.slice(0, 12).map(fmt).join(" ، ") + (ar.length > 12 ? " ، +" + (ar.length - 12) : "") +
        (quiet >= QUIET_MS ? "" : " ⚠️ والقائمةُ لم تسكن حتى السقف — قد يتغيّر العدد") + " ⇒ " + facts);
    } else if (quiet < QUIET_MS) {
      emit(TAG + " ⛔ صفرُ صوتٍ عربيّ **والقائمةُ لم تسكن خلال 7 ثوانٍ** (آخرُ تغيّرٍ @" + changedAt +
        "ms) — **صفرٌ من قائمةٍ تتغيّر صمتٌ لا قياس** (قرار 150): أعِد اللصق بعد ثوانٍ ⇒ " + facts);
    } else if (!local) {
      emit(TAG + " ⛔ صفرُ صوتٍ عربيّ **ولا صوتَ محلّيّاً واحداً بين " + voices.length + "** — أصواتُ النظام لم تصل " +
        "(القائمةُ شبكيّةٌ وحدَها، كالدفعة الأولى المقيسة) ⇒ **«لا يوجد» و«لم يصل» صفرٌ واحد** (قرار 150): " +
        "أعِد اللصق بعد ثوانٍ، وإن تكرّر فاخرج من كروم وأعد تشغيله ⇒ " + facts);
    } else {
      emit(TAG + " ❌ لا صوتَ عربيّ — أضِف صوتاً عربيّاً من إعدادات النظام ثمّ اخرج من كروم وأعد تشغيله " +
        "(يعدّ الأصوات مرّةً في عمر العمليّة؛ وعلى الماك ⌘Q، فإغلاقُ النوافذ لا يُنهيه) ⇒ " +
        "**ولو نُطقت العربيّةُ الآن لاختار كروم صوتاً غيرَ عربيٍّ بصمت** (§٩)" +
        (sus.length ? " ⚠️ وفي «مشتبَه» ما قد يكون عربيّاً بلا وسمه" : "") + " ⇒ " + facts);
    }
  } catch (e) {
    emit(TAG + " ⛔ رميةٌ غيرُ متوقَّعة في المِجَسّ: " + ((e && e.message) || e) +
      " — **عيبٌ في المِجَسّ لا في جهازك**؛ أبلِغ بهذا السطر · سياق=" + ctx + " · بيئة: " + envText);
  } finally {
    if (listening) ss.removeEventListener("voiceschanged", onVC);
  }
})();
