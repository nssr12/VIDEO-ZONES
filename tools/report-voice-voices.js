// عربيٍّ بصمت** (§٩، 📖) ⇒ **فلا خطأَ يُرى، بل عربيّةٌ تُقرأ بلسانٍ آخر.**
// ⇒ **وأصواتُ ماك المالك (Majed · Laila) قيست خارج كروم** (§٩)، **وما يراه كروم
