// يحرس أن كلَّ «قرار N» يُستشهد به يحمله مدخلٌ، ويفرّق رقمَ القرار من رقم البند.
//
// ⭐ **السؤال الذي يجيبه (بلغة المستخدم):** *«حين يُقال «بقرار 87» — أثمّة قرارٌ
// 87 مكتوبٌ يُقرأ، أم رقمٌ يُساق ولا سندَ خلفه؟»*
//
// ── ⛔ مُطلِقُه وقع مرّتين، والثانيةُ هي التي أنشأته (قرار 85) ────────────────
// **الأولى (2026-08-04):** استُشهد بـ«قرار 85» **ولا مدخلَ يحمله** — كُتب نصُّه
// **داخل متن قرار 82** وأُعطي رقماً بلا مدخل. **ورُدَّ الحارسُ يومَها عمداً**
// بقاعدة المالك نفسِها: **الواقعةُ واحدة، وقرار 85 يشترط تكراراً مرصوداً.**
// **والثانية (2026-08-04، في اليوم نفسه):** القرارات **87 · 88 · 89 كُتبت في
// الشجرة ثمّ محاها `git checkout docs/DECISIONS.md`** — شُغِّل لإرجاع شاهدِ شطبٍ
// مؤقّت، **فأخذ معه عملاً غيرَ مُكوَّم لا علاقة له بالشاهد**.
// ⛔ **وأثرُه أخطرُ من فقدها:** كومِتُ `0e3af13` **يقول في متنه «وثلاثةُ قرارات:
// 87 · 88 · 89»** — **دعوىً ليست في فرقه**؛ **والقرارات 91 و92 و93 تستشهد بها**
// ⇒ **فصارت ثلاثُ حجَجٍ لا تُوجد.**
// ⇒ ⭐ **فالمُطلِقُ وقع، والحارسُ يُبنى الآن لا قبل ذلك** — **وأوّلُ اختبارٍ
// لقاعدةٍ أن تُطبَّق حين تُغري بالمخالفة، وثانيه أن تُنفَّذ حين يقع مُطلِقُها.**
//
// ⚠️ **وحدُّه مُعلَن:** يحرس **وجودَ المدخل**، **لا أن نصَّه يقول ما يُنسب إليه**
// — **وذاك حكمٌ بشريّ**، ولا يُدَّعى أن هذا الحارس يضمنه.
const fs = require("fs");
const path = require("path");

let pass = 0, fail = 0;
const check = (name, cond, extra) => cond
  ? (pass++, console.log("  ✅ " + name))
  : (fail++, console.log("  ❌ " + name, extra === undefined ? "" : String(extra).slice(0, 220)));

const ROOT = path.join(__dirname, "..");
const rd = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

// ── أين يعيش المدخل؟ موضعان مشروعان، وهما قسمةُ #81 نفسُها ──────────────────
// **`docs/DECISIONS.md`** لعامّتها، **و`HANDOFF.md` §4** للأحدَ عشرَ التي تُقرأ
// في كل جلسة — **و`tools/test-handoff-split.js` يمنع وجودَ الأحدَ عشرَ في
// الملفّين معاً**، فالبحثُ في الاثنين لا يُرخّص ازدواجاً.
const DEC = rd("docs/DECISIONS.md"), HAND = rd("HANDOFF.md");
const entries = new Set();
for (const src of [DEC, HAND])
  for (const m of src.matchAll(/^\s*(\d{1,3})[بجد]?\.\s/gm)) entries.add(Number(m[1]));

// ── أين يُستشهد؟ الملفّاتُ التي تُقرأ حجّةً ─────────────────────────────────
const FILES = ["docs/DECISIONS.md", "HANDOFF.md", "CLAUDE.md", "AUDIT.md",
  "tools/KNOWN-DEFECTS.md", "tools/CHECKLIST.md",
  ...fs.readdirSync(path.join(ROOT, "tools"))
      .filter((f) => /\.(js|mjs)$/.test(f)).map((f) => "tools/" + f)];

console.log("\n[١] ⭐ كلُّ «قرار N» يُستشهد به يحمله مدخلٌ");
{
  const missing = new Map();
  for (const f of FILES) {
    let src;
    try { src = rd(f); } catch { continue; }
    // ⚠️ **المشطوبُ يُستثنى**: قرار 21 يوجب بقاءَ المسحوب مشطوباً، **وحجّةٌ
    // مشطوبةٌ ليست حجّةً تُساق** — فلا يُطالَب لها بمدخل (وهو قرار 89 مطبَّقاً).
    const live = src.replace(/~~[\s\S]*?~~/g, "");
    for (const m of live.matchAll(/قرار(?:ا|ي)?\s+(\d{1,3})/g)) {
      const n = Number(m[1]);
      if (!entries.has(n)) missing.set(n, (missing.get(n) || new Set()).add(f));
    }
  }
  const list = [...missing.entries()].map(([n, fs2]) => `${n} (في ${[...fs2].slice(0, 2).join(" · ")})`);
  check(`صفر استشهادٍ بلا مدخل — و${entries.size} مدخلاً مرقَّماً`, list.length === 0, list.join(" ⟂ "));
}

console.log("\n[٢] والقرارات المستشهَد بها اليوم موجودةٌ بأعيانها");
{
  // **الثلاثةُ التي فُقدت، تُسمَّى بأرقامها** — فعودتُها محروسةٌ لا مأمولة
  for (const n of [85, 87, 88, 89, 91]) check(`قرار ${n} له مدخل`, entries.has(n), n);
}

console.log("\n[٣] شاهدا قرار 26 — على الحارس نفسه");
{
  const has = (src, n) => [...src.replace(/~~[\s\S]*?~~/g, "")
    .matchAll(/قرار(?:ا|ي)?\s+(\d{1,3})/g)].map((m) => Number(m[1])).includes(n);
  check("موجب: يرى استشهاداً حيّاً", has("يُنفَّذ بقرار 87 بنصّه", 87));
  check("وموجبٌ ثانٍ: ويرى صيغة «قرارا N وM»", has("قرارا 32 و58", 32));
  check("سالب: ولا يرى المشطوب", !has("⛔ ~~بقرار 999~~ — مسحوب", 999));
  check("ورابع: ورقمٌ في نثرٍ لا يسبقه «قرار» لا يُحتسب", !has("وكانت 87 عمليةً", 87));
}

console.log(`\n${fail === 0 ? "✅" : "❌"} نجح ${pass} / فشل ${fail}\n`);
process.exit(fail ? 1 : 0);
