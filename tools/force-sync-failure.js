// مِجَسّ يدويّ: يجعل أوّل كتابة قادمة في storage.sync ترفض مرّة واحدة ثم يعود طبيعياً.
//
// ⚠️ **تشخيصيّ — لا يُشحن.** يُلصق في كونسول **صفحة إعدادات الإضافة**
// (`chrome-extension://<id>/options.html`) أو في كونسول الـ popup.
//
// ── لماذا ──────────────────────────────────────────────────────────────────
// مسارات الفشل لا تُختبر بالانتظار حتى تمتلئ الحصّة: **تُفتعَل مرّة واحدة**.
// وهذا الملف هو **الموضع الواحد** لافتعالها — يستعمله الاختبار اليدوي في
// `docs/PLATFORMS.md` (§15 سابقاً) **والرِكاز الآليّ معاً**، فلا نسختان تتباعدان.
//
// ── كيف يُستعمل ────────────────────────────────────────────────────────────
//   1. افتح صفحة الإعدادات، ثم كونسول المطوّر (⌥⌘I في ماك · F12 في ويندوز).
//   2. الصق **محتوى هذا الملف كاملاً** واضغط Enter.
//   3. يطبع سطراً يؤكّد أنه فعّال ويقول كم كتابة سيرفض.
//   4. نفّذ الفعل المطلوب (اقلب مربّعاً مثلاً) — **أول كتابة ترفض**، والتالية تنجح.
//
// **ورسالته تقول ما فعله بالضبط** — أداة صامتة لا يُعرف أهي عاملة أم لا.
(() => {
  const N = 1;                       // كم كتابة تُرفض (واحدة تكفي للاختبار)
  const MSG = "This request exceeds the MAX_WRITE_OPERATIONS_PER_MINUTE quota.";

  if (window.__vzForceFail) {
    console.warn("⚠️ المِجَسّ مُركَّب سلفاً — أعد تحميل الصفحة قبل إعادة تركيبه.");
    return;
  }
  const orig = chrome.storage.sync.set.bind(chrome.storage.sync);
  let left = N;
  window.__vzForceFail = {
    get left() { return left; },
    restore() { chrome.storage.sync.set = orig; delete window.__vzForceFail;
                console.log("✅ أُعيدت الكتابة إلى طبيعتها."); }
  };
  chrome.storage.sync.set = (...args) => {
    if (left > 0) {
      left--;
      console.log(`⛔ رُفضت كتابة واحدة عمداً (المتبقّي للرفض: ${left}) — المفاتيح: ${Object.keys(args[0] || {}).join(", ")}`);
      return Promise.reject(new Error(MSG));
    }
    return orig(...args);
  };
  console.log(`✅ مِجَسّ افتعال الفشل فعّال — سيرفض **${N}** كتابة قادمة برسالة الحصّة، ثم يعود طبيعياً.`);
  console.log("   وللإلغاء يدوياً: __vzForceFail.restore()");
})();
