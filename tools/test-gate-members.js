// يحرس أن أعضاء بوّابة الكومِت مُعلَنون بعددهم، وأن كلَّ فحصٍ فيها يقول ما يحرسه.
//
// ⚠️ **واسمُه `members` لا `seven`** — كان `test-gate-seven` فصارت البوّابةُ ثمانيةً
// في اليوم نفسِه: **اسمٌ يحمل عدداً يكذب عند أوّل تغيير**، وهو ما نطارده في الوسوم.
//
// ⭐ **السؤال الذي يجيبه (بلغة المستخدم):** *«حين يقال لي «كلُّ الفحوص خضراء
// فالنسخة جاهزة» — أهي فحوصٌ تغطّي ما أستعمله، أم فحصان يحرسان بنداً واحداً
// ويُحرس الباقي بالصدفة؟»*
//
// ── العلّة التي وُلد منها (قرار المالك 2026-08-04، من الجرد) ─────────────────
// ⛔ **بوّابةُ الكومِت كانت أربعة، واثنان منها فقط يُعلنان بنداً في رأسيهما —
// وهو #77 في كليهما.** ⇒ **فكانت البوّابةُ تحرس بنداً واحداً مُعلَناً، وكلَّ ما
// عداه بالصدفة.** ⇒ **وهو البند #99 مطبَّقاً على البوّابة لا على الحرّاس** — ⚠️ **وكان مكتوباً بلفظ القرار وهو بندٌ، فأمسكه `tools/test-decision-refs.js` في أوّل تشغيلة** — ⛔ **ولا يُعاد اللفظُ الخاطئ هنا شرحاً له، وإلا صار الشرحُ مصدراً له** (قرار 93).
//
// ⛔ **والأخطر منه ما كشفه الجرد:** `bench-s69-guards` **كُتب في كومِت #69 نفسِه
// شاهداً على إصلاحه، فاحمرّ بـ#78 وبقي أحمرَ أسابيع** — **لأنه خارج البوّابة**.
// **وعطبُ #103 كان عند المستخدم طوال ذلك، والشاهدُ قائمٌ يقوله ولا سامع.**
// ⇒ ⭐ **شاهدٌ لا يُشغَّل شاهدٌ لا وجود له.**
//
// ── ولماذا يُحرَس العدُّ والإعلان معاً ──────────────────────────────────────
// **العدُّ وحده** يمنع أن تنقص البوّابةُ فحصاً بلا قرار.
// **والإعلانُ وحده** يمنع أن يبقى فحصٌ فيها لا يُعرف ما يحرسه — **فيُحذف يوماً
// لأن أحداً لم يعرف ثمنه**.
// ⚠️ **وحدُّه مُعلَن:** يفحص **وجودَ الإعلان وصحّةَ العدد**، **لا أن الفحص يحرس
// ما يدّعيه** — **وذاك حكمٌ بشريّ**، ولا يُدَّعى أن هذا الحارس يضمنه.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const HANDOFF = fs.readFileSync(path.join(ROOT, "HANDOFF.md"), "utf8");
const CLAUDE = fs.readFileSync(path.join(ROOT, "CLAUDE.md"), "utf8");

let pass = 0, fail = 0;
const check = (name, cond, extra) => cond
  ? (pass++, console.log("  ✅ " + name))
  : (fail++, console.log("  ❌ " + name, extra ?? ""));

// ⛔⭐ **والوسمُ لا يحمل العدد** (قرار 87 · 89): كان «من **الثمانية**» — **فكان
// هذا الحارسُ يفرض عدداً مكتوباً بيدٍ في سبعة ملفّات، وهو عينُ ما مُنع لأجله.**
// ⇒ **فحين تصير البوّابةُ تسعةً، تعديلُ `rig-list` وحده يكفي** — ولا تُحرَّر
// ستّةُ رؤوسٍ بيدٍ كي تعود المجموعة خضراء. **والعددُ يُشتقّ، والوسمُ يدلّ.**
const MARK = "⛔ **من بوّابة الكومِت — يُشغَّل قبل كل كومِت.** ويحرس:";

const main = async () => {
// ⛔ **ولا نسخةَ محلّية من قائمة الثمانية**: تُستورد من `tools/rig-list.mjs`،
// **وهو الموضع الواحد** الذي يُشتقّ منه عددُ البوّابة وعددُ «عند الطلب» معاً.
// **وكانت هنا نسخةٌ ثانية** — وهو داءُ #93 بعينه، في الحارس هذه المرّة.
const { GATE, onDemand, allRigs } = await import("./rig-list.mjs");

console.log(`\n[1] البوّابة ثمانيةٌ — والعدد يُشتقّ ولا يُكتب`);
{
  check("السجلّ يحمل ثمانية", GATE.length === 8, String(GATE.length));
  // ⚠️ **الكتلةُ في `HANDOFF` هي ما يمشي عليه القارئ** — فتُطابق السجلّ
  const m = HANDOFF.match(/### وقبل أي عمل[\s\S]*?```bash\n([\s\S]*?)```/);
  check("كتلةُ `HANDOFF` موجودة", !!m);
  const block = m ? m[1] : "";
  const missing = GATE.filter((g) => !block.includes(g));
  check("وكلُّ الثمانية فيها", missing.length === 0, missing.join(" · "));
  const lines = block.split("\n").filter((l) => l.trim().startsWith("node "));
  check("ولا تاسعَ غيرَ مُعلَن", lines.length === 8, `وُجد ${lines.length}`);
}

console.log("\n[2] وكلُّ رِكازٍ منها يقول ما يحرسه (البند #99 على البوّابة)");
{
  for (const g of GATE.filter((g) => /\.mjs$/.test(g))) {
    const head = fs.readFileSync(path.join(ROOT, "tools", g), "utf8").split("\n").slice(0, 8).join("\n");
    check(`\`${g}\` يُعلن`, head.includes(MARK), head.split("\n")[0].slice(0, 50));
    // **وبنداً بعينه لا جملةً عامّة** — فإعلانٌ بلا بندٍ لا يُقرأ ثمناً
    const line = head.split("\n").find((l) => l.includes(MARK)) || "";
    check(`  ويسمّي بنداً`, /#\d+/.test(line), line.slice(0, 60));
  }
}

console.log("\n[3] وبروتوكولُ النسخة يشترط سحبَ «عند الطلب» — **بالاشتقاق لا بعدد**");
{
  // ⛔ **ما لا يكون في البروتوكول لا يقع** (قرار المالك) — فيُحرَس نصُّه
  check("`CLAUDE.md` فيه قسمُ رفع النسخة", /## Releasing a version/.test(CLAUDE));
  check("ويشترط سحبَ كلِّ ما عند الطلب قبل الرفع",
    /no version is bumped until every on-demand rig has been run/.test(CLAUDE));
  check("وينسب أحمرَها لا يعدّه فقط", /every red attributed/.test(CLAUDE));
  check("والقاعدة مكتوبة: شاهدٌ لا يُشغَّل لا وجود له",
    /witness that is not run is a witness that does not exist/.test(CLAUDE));
  // ⭐ **والمصدرُ يُذكر في الملفّين** — فمن قرأ القاعدة عرف من أين يُطبع العدد
  for (const [n, s] of [["CLAUDE.md", CLAUDE], ["HANDOFF.md", HANDOFF]])
    check(`و\`${n}\` يدلّ على مصدر العدّ (\`rig-list\`)`, /rig-list\.mjs/.test(s));
}

console.log("\n[4] ⛔ ولا عددَ مكتوبٌ بيدٍ لـ«عند الطلب» — **فرقمٌ أُصلحت قيمتُه يتخلّف ثانيةً**");
{
  // **الواقعة:** «الثلاثةُ والعشرون» عاشت في **عشرة مواضع** — ستّةٍ في `HANDOFF`
  // وثلاثةٍ في `CLAUDE.md` **وواحدٍ في هذا الحارس يفرضها** — والمقيس 32.
  // ⚠️ **وحدُّ هذا الفحص مُعلَن:** يمنع **عدداً ملتصقاً بكلمة رِكاز/rigs في سياق
  // القاعدة**، ولا يمنع كلَّ رقمٍ في الملفّ — **فالأرقام المؤرَّخة سجلٌّ لا قاعدة**.
  // **الأرقامُ بالخانات تُمسح في سطور القاعدة وحدها** — لأنها مشروعةٌ في السجلّ.
  const HAND = [
    /\d+\s*(on-demand\s+)?rigs?\b/i,                 // "23 rigs" · "23 on-demand rigs"
    /all\s+\d+\s+on-demand/i,
    /\d+\s*رِكاز/                                     // «23 رِكازاً»
  ];
  // ⭐ **وصيغةُ العدد بالحروف تُمسح في الملفّ كلِّه** — **لا يكتبها أحدٌ إلا لهذي
  // القاعدة**، فلا سجلَّ مؤرَّخاً يستعملها. ⚠️ **وهي تُميّز «الثلاثة» من «الثالثة»
  // عمداً**: `HANDOFF` فيه «الجلسة الثالثة والعشرون» — **وهو ترتيبُ جلسةٍ لا عددُ
  // رِكازات**، فمسحٌ لا يُفرّق بينهما يُحمّر على سطرٍ صحيح (وهو عينُ «وسمٌ أوسعُ
  // من شرطه»).
  const HAND_WORDS = /(الثلاثةُ|الثلاثةِ|الثلاثة|ثلاثةٍ|ثلاثة)\s*و(العشرون|العشرين|عشرين)/;
  // ⛔⭐ **والمشطوب يُستثنى — وهذا ليس تساهلاً بل شرطُ ألّا يتناقض حارسان:**
  // **قرار 21 يوجب أن يبقى الرقم المسحوب مشطوباً بسببه لا محذوفاً صامتاً**، كي
  // يعرف من يقرأ لاحقاً أنه **سُحب** لا أنه لم يُكتب. **فحارسٌ يمنع ذكرَه أصلاً
  // يُلغي قرار 21** ويدفع إلى الحذف الصامت. ⇒ **فيُمسح النصُّ الحيّ وحده.**
  // ⚠️ **وقد أمسك هذا الحارسُ سطرَنا المشطوب في أوّل تشغيلة** — **وسمٌ أوسعُ من
  // شرطه، في الحارس الذي كُتب ليمنع الأوسعَ من شرطه.**
  const live = (s) => s.replace(/~~[\s\S]*?~~/g, "");
  // ⚠️ **ولماذا سطورُ القاعدة وحدها ولا يُمسح الملفّ كلُّه:** المستودع يحمل
  // **أرقاماً مؤرَّخة مشروعة** («37 رِكازاً · 28 منها شاهدُ قبول» في جرد
  // 2026-08-04) — **ورقمٌ في سجلٍّ مؤرَّخ تاريخٌ، ورقمٌ في قاعدةٍ نحكم بها دعوى**.
  // ⇒ **فالمسحُ على ما يحكم، لا على ما يؤرّخ.** ⛔ **وحدُّه مُعلَن: صياغةٌ جديدة
  // للقاعدة بكلماتٍ غير هذي تفلت منه** — وقد أفلتت ستّةٌ من عشرة في أوّل قياس،
  // فوُسِّعت القائمة بالمقيس لا بالتخمين.
  const ruleLines = (s) => s.split("\n").filter((l) =>
    /عند الطلب|on-demand|تُرفع نسخة|ولا نسخة|تُسحب|يُسحب|no version is bumped|Bump version|THE RULE/.test(l));
  for (const [n, s] of [["HANDOFF.md", HANDOFF], ["CLAUDE.md", CLAUDE]]) {
    const bad = ruleLines(live(s)).filter((l) => HAND.some((re) => re.test(l)));
    check(`لا عددَ بيدٍ (بالخانات) في سطور القاعدة بـ\`${n}\``, bad.length === 0,
      bad.map((l) => l.trim().slice(0, 70)).join(" ⟂ "));
    const words = live(s).split("\n").filter((l) => HAND_WORDS.test(l));
    check(`ولا عددَ بالحروف في \`${n}\` كلِّه`, words.length === 0,
      words.map((l) => l.trim().slice(0, 70)).join(" ⟂ "));
  }
  // **والعددُ الحقيقيّ يُشتقّ ويُطابق الملفّات على القرص**
  check("والاشتقاق يعمل: عند الطلب = كلُّ رِكازٍ ليس في البوّابة",
    onDemand().length === allRigs().length - GATE.filter((g) => /\.mjs$/.test(g) &&
      /^(bench|repro|probe)-/.test(g)).length, `${onDemand().length} من ${allRigs().length}`);
  check("ولا رِكازَ في البوّابة يُعدّ مع «عند الطلب»",
    !onDemand().some((r) => GATE.includes(r)));
}

console.log("\n[5] ⛔ ولكلّ رِكازٍ خارج البوّابة **سببُ تأجيله هو، لا سببُ مجموعته**");
{
  // ⭐ **قرار المالك 2026-08-04، والعلّةُ مقيسة:** كان لاثنين وثلاثين رِكازاً
  // **سببٌ واحد** («تحتاج مضيفاً حيّاً») — **ولا يصدق على كلِّها**: منها ما لا
  // يمسّ الشبكة إطلاقاً. ⇒ ⭐ **وسببٌ واحد لمجموعةٍ غير متجانسة بطانيّةٌ تستر
  // أعضاءها** — وهو شكلُ رمز `❌` الذي حمل أربعة معانٍ، في التبرير هذه المرّة.
  const MARK2 = "⛔ **خارج البوّابة — وسببُ تأجيله هو (لا سببُ مجموعته):**";
  const bad = [], thin = [];
  for (const r of onDemand()) {
    const head = fs.readFileSync(path.join(ROOT, "tools", r), "utf8").split("\n").slice(0, 14);
    const i = head.findIndex((l) => l.includes(MARK2));
    if (i < 0) { bad.push(r); continue; }
    // **وسببٌ لا يُقرأ ليس سبباً**: يُشترط نصٌّ بعده لا وسمٌ فارغ
    const body = head.slice(i + 1).join(" ").replace(/^\/\/\s*/, "").trim();
    if (body.replace(/[\/\s]/g, "").length < 40) thin.push(r);
  }
  check(`كلُّ رِكازٍ خارج البوّابة يحمل سببَه (${onDemand().length})`, bad.length === 0,
    bad.join(" · "));
  check("وسببُه نصٌّ يُقرأ لا وسمٌ فارغ", thin.length === 0, thin.join(" · "));
  // ⛔ **ولا يُقبل السببُ الجامع المسحوب** — فمن نسخه إلى رِكازٍ عاد إلى البطانيّة
  const blanket = onDemand().filter((r) => {
    const h = fs.readFileSync(path.join(ROOT, "tools", r), "utf8").split("\n").slice(0, 14).join(" ");
    return /خارج البوّابة — وسببُ تأجيله/.test(h) &&
           /^[^\n]*تحتاج مضيفاً حيّاً\s*\.?\s*$/.test(h.split(MARK2)[1] || "");
  });
  check("ولا أحدَ يُعيد السببَ الجامع وحده", blanket.length === 0, blanket.join(" · "));
}

console.log("\n[6] شاهدا قرار 26 — على الحارس نفسه");
{
  const hasMark = (h) => h.includes(MARK) && /#\d+/.test(h);
  check("موجب: رأسٌ مُعلَنٌ بندُه يُقبل", hasMark(`// x\n// ${MARK} **#69** — كذا`));
  check("سالب: ورأسٌ بلا الوسم يُرفض", !hasMark("// فحصٌ ما\n// بلا وسم"));
  check("وثالث: ووسمٌ بلا بندٍ يُرفض", !hasMark(`// ${MARK} شيءٌ مهمّ`));
  // ورابع: قائمةٌ بستّة تُحمَّر — فالعدد يُقاس لا يُفترض
  check("ورابع: سبعةٌ تُحمَّر", ["a","b","c","d","e","f","g"].length !== 8);
  // ⭐ **وخامسٌ لفحص العدد المكتوب: يُحمّر على العبارة التي كانت، ويمرّ على بديلها**
  const HAND2 = /\d+\s*(on-demand\s+)?rigs?\b/i;
  check("وخامس: «all 23 on-demand rigs» تُحمَّر",
    HAND2.test("no version is bumped until all 23 on-demand rigs have been run"));
  check("وسادس: والبديلُ المشتقّ يمرّ",
    !HAND2.test("no version is bumped until every on-demand rig has been run"));
  // ⭐ **وسابعٌ وثامن: المشطوبُ يمرّ والحيُّ يُحمَّر** — فقرار 21 وهذا الحارس لا يتناقضان
  const strip = (x) => x.replace(/~~[\s\S]*?~~/g, "");
  const W2 = /(الثلاثةُ|ثلاثةٍ)\s*و(العشرون|عشرين)/;
  check("وسابع: عددٌ بالحروف **مشطوبٌ** يمرّ (قرار 21)",
    !W2.test(strip("⛔ ~~السببُ المكتوب لثلاثةٍ وعشرين رِكازاً~~ — مسحوب")));
  check("وثامن: والحيُّ يُحمَّر",
    W2.test(strip("ولا تُرفع نسخةٌ حتى تُسحب الثلاثةُ والعشرون")));
}

console.log(`\n${fail === 0 ? "✅" : "❌"} نجح ${pass} / فشل ${fail}\n`);
process.exit(fail ? 1 : 0);
};
main();
