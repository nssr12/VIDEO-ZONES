// أحكامُ اجتياح الضوابط في قسم [٣] — **دالّةٌ نقيّة، كي يُحرَس الحكمُ بلا متصفّح**.
//
// ⭐ **السؤال الذي تجيبه (بلغة المستخدم):** *«حين تقول البوّابةُ إن ضوابط
// الإعدادات سليمة — أعن ستّةٍ وأربعين تحقّقت، أم عن لا شيء؟»*
//
// ── لماذا خرجت من `bench-options-page.mjs` إلى هنا ──────────────────────────
// **الحكمُ يُحرَس، والتشغيلُ يحتاج كروم.** فلو بقي الحكم داخل الرِكاز لَما أمكن
// أن يُحرَس إلا بمتصفّحٍ حيّ، **وحارسٌ يحتاج مضيفاً هو حارسٌ يُشغَّل عند الطلب**
// — وقد نامت #103 في واحدٍ منها أسابيع. ⇒ **فالحكمُ هنا نقيٌّ يُحرَس في المجموعة
// قبل كل كومِت، والقياسُ هناك حيٌّ يُطعمه.** ⛔ **ولا نسخةَ ثانية منه:** الرِكاز
// يستورده، ولا يُعيد كتابة شرطٍ واحد (وهو داءُ #93 بعينه).
//
// ── العلّتان اللتان وُلد منهما (2026-08-04، بعد إغلاق شطرَي #93) ─────────────
// **صنفُهما واحد: بوّابةٌ خضراء عن لا شيء** — وهو الصنف الذي رُصد **أربع مرّات
// في اليوم نفسه وفي هذا الملفّ بعينه**، فلم يعد شكّاً (قرار المالك: **القاعدة
// «بندٌ بلا عَرَضٍ مرصود شكّ» تُقاس بالصنف لا بالحالة**).
//   1. **`sw.length` كان يُطبع ولا يُؤكَّد** ⇒ اجتياحٌ خاوٍ (لو رجع استعلامُ
//      المعرّفات فارغاً) **يُصفّي الشروط الثلاثة إلى صفر فتُطبع خضراء**، و[٤]
//      يعدّ بنداءٍ آخر فلا يُمسكها.
//   2. **و«مُتخطّى» كان سطرَ طباعةٍ لا شرطاً** ⇒ ضابطٌ يصير `disabled` أثناء
//      الاجتياح **يخرج من الشروط الثلاثة كلِّها صامتاً**. ⚠️ **ومُطلِقُه فعلٌ
//      عاديّ لا افتراض:** `volumeDuration` عند `0` يُعطّل `speedBadgeEnabled`،
//      **وهو يُجتاح بعده**.
// ⇒ **وليستا آلةً جديدة بل إعلانُ البوّابة عمّا تحقّقت منه** (قرار المالك).

// `sweep`: صفوفُ الاجتياح · `drawn`: ما عُدّ مرسوماً بنداءٍ مستقلّ.
// تُرجع صفوفَ حكمٍ `{ name, ok, extra }` — والرِكاز يطبعها، ولا يُقرّر شيئاً.
export function sweepVerdicts(sweep, drawn) {
  const sw = Array.isArray(sweep) ? sweep : [];
  const expected = Number(drawn?.clean || 0) + Number(drawn?.timing || 0);
  const threw = sw.filter((s) => s.threw > 0);
  const notSaved = sw.filter((s) => s.ok && !s.changed);
  const skipped = sw.filter((s) => s.skipped || s.why);
  const snapped = sw.filter((s) =>
    s.ok && s.wanted != null && s.shown != null && s.wanted !== s.shown);

  return [
    // ⛔ **أوّلُ حكمٍ لأنه شرطُ صدق البقيّة**: الثلاثةُ بعده تُصفّي مصفوفةً،
    // **ومصفوفةٌ خاوية تُرضيها كلَّها**. فيُقاس العددُ بمصدرٍ ثانٍ (ما رُسم)،
    // **لا بنفسه** — فعددٌ يشهد لنفسه لا يشهد.
    { name: "[٣] ⭐ والاجتياح شمل ما رُسم — فلا خضرةَ عن لا شيء",
      ok: sw.length > 0 && expected > 0 && sw.length === expected,
      extra: { اجتيح: sw.length, رُسم: expected } },

    { name: "[٣] صفر استثناء عند التفاعل",
      ok: threw.length === 0,
      extra: threw.slice(0, 4).map((s) => `${s.id}: ${String(s.msg).split("\n")[0].slice(0, 60)}`) },

    { name: "[٣] وكلُّ تبديلٍ يصل التخزين",
      ok: notSaved.length === 0,
      extra: notSaved.map((s) => s.id).slice(0, 12) },

    // ⭐ **#89: المعروض يطابق المطلوب** — وإلا فالواجهة تكذب على التخزين
    { name: "[٣] ⭐ والمعروض يطابق المطلوب (لا يقفز الضابط بعد ضبطه)",
      ok: snapped.length === 0,
      extra: snapped.map((s) => s.id + ": طُلب " + s.wanted + " فعُرض " + s.shown).slice(0, 6) },

    // ⛔ **شرطٌ يُحمّر لا سطرٌ يُطبع**: المُتخطّى **خارجُ الشروط الثلاثة كلِّها**،
    // فسطرُ طباعةٍ عنه يجعل خروجَه بلا أثرٍ في الحكم — **وهو الغيابُ يُقرأ إثباتاً**.
    { name: "[٣] ⭐ ولا ضابطَ خرج من الاجتياح (معطَّلاً أو غيرَ مرسوم أو رامياً)",
      ok: skipped.length === 0,
      extra: skipped.map((s) => `${s.id}: ${s.why || "معطَّل"}`).slice(0, 12) }
  ];
}
