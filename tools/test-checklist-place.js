// يحرس أن خطوات التحقّق الميدانيّ تعيش في tools/CHECKLIST.md وحدها لا في §17.
//
// ⭐ **السؤال الذي يجيبه (بلغة المستخدم):** *«حين أمشي على قائمة التحقّق، أأجد خطواتها كلَّها في موضعٍ واحد؟ (والمستخدم هنا المالك)»*
//
// ── العلّة التي وُلد منها (قرار 41، 2026-08-03) ──────────────────────────────
// كُتبت الخطوات الثلاث والثلاثون في `HANDOFF.md` §17 **مستوفيةً شرط «موضعٌ
// واحد» شكلاً**، وبدأت عند السطر 2158 من ملفٍّ طوله 2347. **ففتح المالك §17
// فقرأ التمهيد والسؤال المفتوح وظنّ أن لا خطوات** — والخطوات موجودة.
// ⇒ **الوحدة تحقّقت والبلوغ لم يتحقّق، وهما شرطان لا شرط.**
//
// **وهو الفشل نفسه الذي شكا منه المالك في صفحة الإعدادات** (#77): أداةٌ صحيحة
// تمنع صاحبها من استعمالها. ⚠️ **والدرس أن «صحيح» و«صالح للاستعمال» حكمان
// منفصلان** — والأول لا يُثبت الثاني، ولا يقيسه اختبارٌ يقرأ المحتوى وحده.
//
// **والحارس نصّيّ لأن العلّة نصّية:** لا يمنع الخطأ في الكتابة، **يمنع عودته**.
// فمن نسخ خطوةً إلى §17 بحسن نيّة (وهو ما يقع حين يُشرح شيءٌ في مكانه) يرى
// الأحمر في التوّ.
//
// ── شاهدا القبول (قرار 26) ──────────────────────────────────────────────────
// **سالب:** §17 الحقيقيّ **يجب أن يمرّ**. **موجب:** نصٌّ مُفتعَل فيه خطوةٌ
// مرقّمة **يجب أن يُحمّره** — وإلا فحارسٌ لا يُثبت أنه يرى.
// **والمراسي محروسة** (قرار 33): تعذُّر إيجاد §17 أو الملفّ **يُفشل الاختبار**
// بدل أن يُقرأ سلامة — قسمٌ لم يُقرأ يخلو من كلّ شيء.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CHECKLIST = "tools/CHECKLIST.md";
let pass = 0, fail = 0;
const ok = (cond, msg) => { if (cond) { pass++; } else { fail++; console.log(`  ❌ ${msg}`); } };

// خطوةٌ مرقّمة = سطر يبدأ برقم (وحرفٍ عربيّ اختياريّ) ثمّ نقطة ثمّ فراغ.
// ⚠️ **مقصورةٌ على §17 عمداً**: `HANDOFF.md` مملوءٌ بقوائم مرقّمة مشروعة —
// القرارات ومنصّات §8 و§9 و§10 — فحارسٌ يعمّ الملفّ **يُحمّر ما لا علّة فيه**،
// ومجموعةٌ حمراء دائماً مجموعةٌ ميتة (قرار 20).
const STEP_RE = /^\s{0,3}\d+[أ-ي]?\.\s/;

// يقتطع §17 حتى العنوان التالي من مستواه أو نهاية الملفّ
function section17(src) {
  const lines = src.split("\n");
  const a = lines.findIndex((l) => l.startsWith("## 17."));
  if (a === -1) return null;                       // المرساة سقطت
  let b = lines.length;
  for (let i = a + 1; i < lines.length; i++) {
    if (lines[i].startsWith("## ")) { b = i; break; }
  }
  return lines.slice(a, b);
}

function numberedSteps(sectionLines) {
  return sectionLines
    .map((l, i) => ({ l, i }))
    .filter((x) => STEP_RE.test(x.l));
}

console.log("\n[1] الشاهد السالب — §17 الحقيقيّ يجب أن يمرّ");
// ⚠️ **المرساة انتقلت بقسمة #81، فتُصلَح المرساة لا التأكيد (قرار 33):**
// §17 صار في `docs/HISTORY.md` — **والحارس يقرأ من حيث هو، ويُفشل إن لم يجده
// في أيٍّ منهما**، فلا يمرّ صامتاً على مرساةٍ ساقطة.
const HOMES = ["HANDOFF.md", "docs/HISTORY.md"];
const handoff = HOMES.map((f) => {
  try { return fs.readFileSync(path.join(ROOT, f), "utf8"); } catch { return ""; }
}).find((t) => /^## 17\./m.test(t)) || fs.readFileSync(path.join(ROOT, "HANDOFF.md"), "utf8");
const sec = section17(handoff);
ok(sec !== null, "تعذّر إيجاد `## 17.` في HANDOFF.md ولا في docs/HISTORY.md — **المرساة سقطت، أصلِح المرساة لا التأكيد** (قرار 33)");
if (sec === null) {
  console.log(`\n❌ فشل: ${fail} · نجح: ${pass}`);
  process.exit(1);
}
const found = numberedSteps(sec);
ok(found.length === 0,
   `خطوات مرقّمة عادت إلى §17 (${found.length}): ` +
   found.slice(0, 3).map((x) => `«${x.l.trim().slice(0, 40)}…»`).join(" · ") +
   ` — **موضعها ${CHECKLIST}** (قرار 41)`);

// والإشارة شرطٌ مقابل: قسمٌ بلا خطوات وبلا إشارة **يترك القارئ بلا طريق**،
// وهو العطب الأصليّ بثوبٍ أسوأ.
ok(sec.some((l) => l.includes(CHECKLIST)),
   `§17 لا يشير إلى ${CHECKLIST} — **قسمٌ بلا خطوات وبلا طريقٍ إليها أسوأ من الدفن**`);

console.log("\n[2] الملفّ المستقلّ — يوجد ويحمل المراسي");
const clPath = path.join(ROOT, CHECKLIST);
ok(fs.existsSync(clPath), `${CHECKLIST} غير موجود — **الخطوات لا موضع لها**`);
if (fs.existsSync(clPath)) {
  const cl = fs.readFileSync(clPath, "utf8");
  const clSteps = numberedSteps(cl.split("\n"));
  ok(clSteps.length > 0, `${CHECKLIST} بلا خطوة مرقّمة واحدة — **نُقلت إلى فراغ**`);
  // ⛔ **انقلبت المراسي بقرار المالك 2026-08-03، والانقلاب مقصود:** كانت أرقام
  // §17 (`1` · `10` · `20` · `25` · `33`)، **وصار للمالك ترقيمٌ متّصل خاصّ به**
  // (`م1`–`م18`) لأن **قائمةً فيها فجوات أرقام يظنّ الماشي عليها أنه أسقط خطوة**.
  // ⚠️ **ولم تُعدَّل لتمرّ بل انقلبت لأن المطلوب انقلب** (قرار 33) — والتغطية
  // باقية: **نقلٌ ناقص ما زال يُحمّر**، والخريطة القديمة⇄الجديدة محروسة أدناه.
  // ⚠️⭐ **وسقطت `م1` من المراسي 2026-08-07 (#112) لأنها انتقلت إلى الآليّ** —
  // **لا لتمرّ**: خطوةٌ صارت رِكازاً لا تبقى مرساةً في قائمةٍ يدويّة، **وإبقاؤها
  // يشترط وجودَ ما رُفع عمداً.** ⇒ **والمرساةُ الباقية تُختار من خطوةٍ ما زالت
  // بيد المالك** (`م6` · `م11` · `م18`)، **والحارسُ يُحمّر إن رُفعت هي كذلك بلا
  // تعديلٍ هنا** — **فالرفعُ يبقى فعلاً مقصوداً لا انزلاقاً.**
  for (const anchor of ["**م6.**", "**م11.**", "**م18.**"]) {
    ok(cl.includes(anchor), `المرساة «${anchor.trim()}» غائبة عن ${CHECKLIST} — **نقلٌ ناقص**`);
  }
  // **والخريطة شرطٌ لا تحسين:** بلاغات المالك السابقة بأرقام §17 تبقى مقروءةً بها
  ok(/الخريطة: الجديد ⇄ القديم/.test(cl),
     "خريطة الترقيم غائبة — **فبلاغات المالك السابقة (13 · 22ه · 20) تصير غير مقروءة**");
  ok(/\| \*\*م1\*\* \| 1 \|/.test(cl), "الخريطة لا تربط م1 بـ1 — **مرساةٌ في الخريطة نفسها**");
  ok((cl.includes("HANDOFF.md") || cl.includes("HISTORY.md")) && /§17/.test(cl),
     `${CHECKLIST} لا يشير إلى §17 — **الحجج والشروط لا طريق إليها**`);
}

console.log("\n[3] الشاهد الموجب — نصٌّ مُفتعَل يجب أن يُحمّره الحارس");
const fakeBack = ["## 17. عنوان", "", "> تمهيد", "", "1. افعل كذا ⇒ المتوقَّع كذا", "", "## 18. غيره"];
const fakeFound = numberedSteps(section17(fakeBack.join("\n")));
ok(fakeFound.length === 1, "الحارس لم يرَ خطوةً مرقّمة عادت إلى §17 — **لا يُصدَّق خضاره**");

const fakeSub = ["## 17. عنوان", "", "22ه. بدّل الضابط ⇒ لا يتغيّر إلا حقلُه", "", "## 18."];
ok(numberedSteps(section17(fakeSub.join("\n"))).length === 1,
   "الحارس لم يرَ خطوةً فرعية بحرف (22ه) — **والحروف هي شكل الخطوات الغالب**");

// وسالبٌ ثانٍ: ما ليس خطوةً لا يُحمَّر — وإلا صار الحارس ضجيجاً يُتجاهَل
const fakeSafe = ["## 17. عنوان", "", "> **(١)** شرطٌ أوّل", "> **(٢)** شرطٌ ثانٍ",
                  "", "انظر [`tools/CHECKLIST.md`](tools/CHECKLIST.md)", "", "## 18."];
ok(numberedSteps(section17(fakeSafe.join("\n"))).length === 0,
   "الحارس حمّر شروطاً بصيغة (١) — **حارسٌ يُحمّر السليم يُدرَّب الناس على تجاهله**");

// وسقوط المرساة يُرجع null لا قسماً فارغاً يُقرأ نظيفاً
ok(section17("## 16. شيء آخر\n\nنصّ") === null,
   "ملفٌّ بلا §17 قُرئ نظيفاً بدل أن تسقط مرساته");

// الصيغة هي التي يفهمها `tools/run-tests.js` — ملفٌ بخرْج آخر يُحسب **مجهولاً
// لا صفراً**، فيُحمّر المجموعة بدل أن يُتخطّى صامتاً.
console.log(`\n${fail === 0 ? "✅" : "❌"} نجح ${pass} / فشل ${fail}\n`);
process.exit(fail ? 1 : 0);
